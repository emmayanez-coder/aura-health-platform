import assert from 'node:assert/strict';
import {mountAnswerVoice} from './dist/answer-voice.mjs';
const elements=new Map();
globalThis.document={getElementById(id){if(!elements.has(id))elements.set(id,{checked:false,textContent:'',classList:{toggle(){}},removeAttribute(){},load(){}});return elements.get(id);}};
const $=id=>document.getElementById(id);
let requests=[],played=0,paused=0;
globalThis.Audio=class {pause(){paused++;}play(){played++;return Promise.resolve();}};
globalThis.fetch=async(url,options)=>{requests.push({url,options});return {ok:true,headers:{get:()=> 'application/json'},json:async()=>options.method==='POST'?{audio:btoa('test-audio')}:{nonce:'test-nonce'}};};
const voice=mountAnswerVoice();
voice.received('Do not autoplay.');assert.equal(requests.length,0);
await voice.speak('Manual answer.');assert.equal(played,1);
assert.deepEqual(JSON.parse(requests[1].options.body),{kind:'answer',text:'Manual answer.',speechConsent:true});
assert.equal(requests[1].options.headers['X-AURA-Access-Code'],undefined);
$('answerVoiceStop').onclick();assert.ok(paused>0);assert.equal($('answerVoiceStatus').textContent,'Speech stopped.');
$('answerVoiceAuto').checked=true;voice.received('Automatic answer.');
await new Promise(resolve=>setImmediate(resolve));assert.equal(played,2);
assert.equal(JSON.parse(requests.at(-1).options.body).text,'Automatic answer.');
$('answerVoiceAuto').checked=false;$('answerVoiceAuto').onchange();
const before=requests.length;voice.received('No autoplay.');assert.equal(requests.length,before);
voice.clear();assert.equal($('answerVoiceAuto').checked,false);
await voice.speak('Manual answer.');assert.equal(requests.length,before+2);
console.log('PASS: manual and optional automatic cloud speech, payload, public access, stop, disabled autoplay, and cache clearing.');
