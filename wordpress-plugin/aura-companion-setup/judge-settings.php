<?php
if(!defined('ABSPATH'))exit;
function aura_judge_settings_form(): void {
    $settings=get_option('aura_judge_access_v1',[]);
    echo '<hr><h2>Judge access without WordPress accounts</h2><p>Share a separate access code with judges. Never share your WordPress password or API key. Existing site-wide AI limits still apply.</p>';
    echo '<form method="post" action="'.esc_url(admin_url('admin-post.php')).'">';
    wp_nonce_field('aura_judge_save');
    echo '<input type="hidden" name="action" value="aura_judge_save">';
    echo '<p><label><input type="checkbox" name="enabled" value="1" '.checked(($settings['enabled']??false),true,false).'> Enable judge access</label></p>';
    echo '<p><label>New judge code (20–128 characters)<br><input type="password" name="judge_code" maxlength="128" autocomplete="new-password" class="regular-text"></label></p><p>Choose a unique code, preferably generated by a password manager. Copy it privately before saving. Leave blank to retain the existing code. Only a password hash is stored.</p>';
    echo '<p><label>Last access day (UTC, up to 30 days ahead)<br><input type="date" name="expires" required value="'.esc_attr(gmdate('Y-m-d',max(time(),(int)($settings['expires']??(time()+7*86400)))-1)).'"></label></p>';
    echo '<p>Status: '.(!empty($settings['hash'])?'A code is saved; it is never displayed.':'No code saved.').'</p><button class="button button-primary" type="submit">Save judge access</button></form>';
}
add_action('admin_post_aura_judge_save',function(){
    if(!current_user_can('manage_options'))wp_die('Administrator required.');
    if(($_SERVER['REQUEST_METHOD']??'')!=='POST')wp_die('POST required.');
    check_admin_referer('aura_judge_save');
    $old=get_option('aura_judge_access_v1',[]);
    $raw=$_POST['judge_code']??'';$date=$_POST['expires']??'';
    if(!is_string($raw)||!is_string($date))wp_die('Invalid input.');
    $code=trim(wp_unslash($raw));
    if($code!==''&&(strlen($code)<20||strlen($code)>128))wp_die('Use a code between 20 and 128 characters.');
    $day=DateTimeImmutable::createFromFormat('!Y-m-d',$date,new DateTimeZone('UTC'));
    if(!$day||$day->format('Y-m-d')!==$date)wp_die('Choose a valid expiry date.');
    $expires=$day->modify('+1 day')->getTimestamp();
    if($expires<=time()||$expires>time()+31*86400)wp_die('Choose an expiry date within the next 30 days.');
    $hash=$code!==''?wp_hash_password($code):($old['hash']??'');
    $enabled=($_POST['enabled']??'')==='1';
    if($enabled&&$hash==='')wp_die('Enter a judge code before enabling access.');
    $settings=['enabled'=>$enabled,'hash'=>$hash,'expires'=>$expires];
    update_option('aura_judge_access_v1',$settings,false);
    if(get_option('aura_judge_access_v1',[])!==$settings)wp_die('Could not save judge access.');
    wp_safe_redirect(admin_url('options-general.php?page=aura-companion-setup&aura_notice=saved'));exit;
});
