import assert from 'node:assert/strict';
import fs from 'node:fs';
import {interpret,usableAssessment,compareFollowup} from './dist/guidance.mjs';
import {scoreReadiness,demoInput} from './dist/aura_score.mjs';
const now=Date.parse('2026-11-14T18:00:00Z');
const before={demo:false,deviceKey:'kyto:bluetooth',rrEncoding:'bluetooth',durationSeconds:300,context:'resting',measuredAt:new Date(now-600000).toISOString(),hrBpm:72,rmssdMs:32,quality:{hrCoverage:.95,rrCoverage:.95}};
const loop={status:'awaiting',before,completedAt:new Date(now-300000).toISOString()};
const after={...structuredClone(before),measuredAt:new Date(now).toISOString(),hrBpm:70,rmssdMs:34};
assert.equal(usableAssessment(before,now),true);
for(const a of [{...before,demo:true},{...before,measuredAt:new Date(now+1).toISOString()},{...before,measuredAt:new Date(now-86400000).toISOString()},{...before,quality:{hrCoverage:.79}}])assert.equal(usableAssessment(a,now),false);
const result=compareFollowup(loop,after,now);assert.equal(result.hrDeltaBpm,-2);assert.equal(result.rmssdDeltaMs,2);
assert.equal(compareFollowup(loop,{...after,rmssdMs:null},now).rmssdDeltaMs,null);
assert.throws(()=>compareFollowup({...loop,status:'action'},after,now),/Complete/);
assert.throws(()=>compareFollowup(loop,{...after,deviceKey:'other'},now),/same sensor/);
assert.throws(()=>compareFollowup(loop,{...after,rrEncoding:'kyto-ms'},now),/same sensor/);
assert.throws(()=>compareFollowup(loop,{...after,measuredAt:new Date(now-1).toISOString()},now),/after marking/);
assert.throws(()=>compareFollowup(loop,{...after,demo:true},now),/fresh/);
const view=interpret(demoInput,scoreReadiness(demoInput));assert.equal(view.title,'Review changes in your routine');assert.equal(view.facts.length,3);
const empty={metrics:{},baseline:{validDays:0},eligible:{}};
const missing=interpret(empty,scoreReadiness(empty));assert.equal(missing.facts.length,0);assert.equal(missing.title,'More information needed');
const html=fs.readFileSync(new URL('./dist/index.html',import.meta.url),'utf8');
const code=fs.readFileSync(new URL('./dist/guidance.mjs',import.meta.url),'utf8');
const ids=[...html.matchAll(/id="([^"]+)"/g)].map(m=>m[1]);
for(const [,id] of code.matchAll(/(?:\$|put)\('([^']+)'/g))assert.ok(ids.includes(id),id);
for(const [,id] of html.matchAll(/href="#([^"]+)"/g))assert.ok(ids.includes(id),'Broken anchor '+id);
const app=fs.readFileSync(new URL('./dist/app.mjs',import.meta.url),'utf8');
assert.ok(app.includes('reassessmentLoops:guidance.export()'));
assert.ok(app.includes('guidance.clear()'));
console.log('PASS: missing-data interpretation, complete comparison, stale/demo/quality/device/timing guards, HR-only comparison, UI references, anchors, export and clearing.');
