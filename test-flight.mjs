assert.throws(()=>detectBeats(invalid),/Invalid/);
assert.throws(()=>detectBeats(synthetic,128));
const file=new URL('./dist/data/flight-crew-ecg.json',import.meta.url);
const bytes=fs.readFileSync(file),data=JSON.parse(bytes);
const report=replayFlightCrew(data);
assert.ok(data.provenance.archiveSHA256.match(/^[a-f0-9]{64}$/));
assert.equal(data.samples.length,79360);
assert.equal(data.samples.at(-1)[0]-data.samples[0][0],310-1/256);
assert.equal(report.summary.hr,null,'Low coverage must withhold HR');
