import assert from 'node:assert/strict';
import fs from 'node:fs';
import crypto from 'node:crypto';
import {detectBeats,replayFlightCrew} from './dist/flight-crew.mjs';
const synthetic=Array.from({length:310*256+1},(_,i)=>{
  const t=i/256, phase=t-Math.round(t);
  return [t,Math.exp(-((phase/.012)**2))+.001*Math.sin(t*17)];
});
const known=replayFlightCrew({schema:'aura-flight-crew-ecg-v1',sampleRate:256,samples:synthetic,provenance:{synthetic:true}});
assert.ok(Math.abs(known.summary.hr-60)<.01,'Known 60 BPM train');
assert.ok(known.summary.rmssd<.01,'Constant RR should produce zero RMSSD');
assert.ok(known.summary.rrCoverage>.98);
assert.equal(detectBeats(synthetic.map(([t])=>[t,0])).peaks.length,0);
